"""Writes the vocabulary of the shared labels package from scripts/truth_vocabulary.tsv (DECISIONS 868).

usage: python3 scripts/gen_shared_labels.py           write packages/shared_labels/lib/src/vocabulary.g.dart
       python3 scripts/gen_shared_labels.py --check   exit 1 when that file is not what the vocabulary gives now

One vocabulary for the laptop's truth table, eeg_tracker and utof_tracker: a label, source or confidence is added in
the TSV, then this is run again. Standard library only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import truth  # noqa: E402

OUT = HERE.parent / "packages" / "shared_labels" / "lib" / "src" / "vocabulary.g.dart"


def dart(s: str | None) -> str:
    """A Dart string literal (or null)."""
    return "null" if s is None else json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def name(word: str) -> str:
    """`headband_off` -> `headbandOff`."""
    return re.sub(r"_(\w)", lambda m: m[1].upper(), word)


def source(v: truth.Vocabulary) -> str:
    out = ["// GENERATED by scripts/gen_shared_labels.py from scripts/truth_vocabulary.tsv. Do not edit: change the TSV",
           "// and run the script again (analysis/tests/test_confirm.py fails when this file is stale).",
           "// dart format off", "part of 'vocabulary.dart';", "",
           "/// Every label of the vocabulary by name (`Labels.walking`), and all of them in the TSV's order.",
           "abstract final class Labels {"]
    for lab in v.labels.values():
        also = ", ".join(dart(a) for a in lab.also)
        out.append(f"  static const Label {name(lab.id)} = Label({dart(lab.id)}, {dart(lab.kind)}, {dart(lab.unit)}, "
                   f"[{also}], {dart(lab.description)});")
    out.append("")
    out.append("  static const List<Label> all = [" + ", ".join(name(i) for i in v.labels) + "];")
    out.append("}")
    for const, what, items in (("labelKinds", "kind", v.kinds), ("labelSources", "source", v.sources),
                               ("labelConfidences", "confidence", v.confidences)):
        out += ["", f"/// Every {what} of the vocabulary and what it means.", f"const Map<String, String> {const} = {{"]
        out += [f"  {dart(k)}: {dart(d)}," for k, d in items.items()]
        out.append("};")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = source(truth.read_vocabulary())
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run python3 scripts/gen_shared_labels.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
